func TestParse(t *testing.T) {
	if !IsStatement([]byte(sample)) || IsStatement([]byte("Виписка по картці;Рахунок: UA583003350000000026001234567")) {
		t.Fatal("IsStatement")
	}
	r, err := ParseCSV([]byte("\xef\xbb\xbf" + sample))
	if err != nil {
		t.Fatal(err)
	}
	if r.IBAN != "UA129358710000067401001111111" || r.CardNumber != "5175****0170" || r.Balance != 0.18 {
		t.Fatalf("шапка: %+v", r)
	}
	tx := r.Transactions
	if len(tx) != 8 {
		t.Fatalf("n=%d", len(tx))
	}
	if tx[0].Amount != 660000 || tx[0].CounterName != "IVANENKO IVAN" || tx[0].MCC != 6536 {
		t.Fatalf("зачисление: %+v", tx[0])
	}
	if tx[0].CounterIban != "4149****5262" || tx[5].CounterIban != "4149****5262" || tx[1].CounterIban != "" {
		t.Fatal("карта контрагента")
	}
	if tx[1].Amount != 5000 || tx[3].Amount != -500000 || tx[5].Amount != -109082 {
		t.Fatalf("суммы: %d %d %d", tx[1].Amount, tx[3].Amount, tx[5].Amount)
	}
	if tx[4].CounterName != "НОВА ПОШТА" || tx[2].CounterName != "Петренко Петро Петрович" {
		t.Fatalf("получатель: %q %q", tx[4].CounterName, tx[2].CounterName)
	}
	if tx[6].ID == tx[7].ID {
		t.Fatal("одинаковые операции в одну минуту должны получить разные id")
	}
	// сумма всех операций = остаток на конец (начальный 0)
	var sum int64
	for _, x := range tx {
		sum += x.Amount
	}
	if sum != 18 {
		t.Fatalf("сумма операций %d ≠ остатку 18 коп.", sum)
	}
	// киевское время: 26.09.2026 14:44 EEST = 11:44 UTC
	if tx[0].Time != 1790423040 {
		t.Fatalf("tz: %d", tx[0].Time)
	}
}
