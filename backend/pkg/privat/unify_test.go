func TestUnifyLookalikes(t *testing.T) {
	a := extractCounterparty(`Зарахування переказу, УКРАЇНА, термінал CS980400, адреса терміналу -, документ № P24A4650082824D7626, платник ІВАНЕНКО МАРІЯ ПЕТРІВНА, номер картки/рахунку платника 545708******4946, банк платника АТ КБ "ПРИВАТБАНК", код ІД НБУ 305299, Коментар до платежу: -`)
	b := extractCounterparty(`Зарахування переказу, УКРАЇНА, термінал CS980400, адреса терміналу -, документ № P24A4650082824D7626, платник ІВАНЕНКО МАРІЯ ПЕТРІВНА, номер картки/рахунку платника 545708******4946, банк платника АТ КБ "ПРИВАТБАНК", код ІД НБУ 305299, Коментар до платежу: -`)
	if a != b || a != "ІВАНЕНКО МАРІЯ ПЕТРІВНА" {
		t.Fatalf("%q != %q", a, b)
	}
	got := extractCounterparty(`АЗС, УКРАЇНА, термінал 52307312, адреса терміналу -, документ № MDUQFZ1PL0102, 516875****29, отримувач WOG 2926, банк отримувача -, код ІД НБУ -, Коментар до платежу: -`)
	if got != "WOG 2926" {
		t.Fatalf("latin names must stay: %q", got)
	}
}

