// Строки зелёного пуша «Снято» после обхода банков. Автозапись в источники (галочка у «Разведать») добавляет строку
// про то, сколько файлов-источников обновлено; без галочки строки нет.
export const syncOkLines = (last) => {
  const lines = [`Запросов к банку: ${last.requests}`]
  if (last.autosave) lines.push(last.saved > 0 ? `Записано в источники: ${last.saved}` : 'Источники уже актуальны')
  return lines
}
